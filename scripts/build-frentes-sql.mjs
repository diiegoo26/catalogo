// Builds supabase/equipaciones-2026-27-frentes.sql: one idempotent UPDATE per product
// that reduces products.images to the FRONT VIEW of each FootyLogos kit variant.
//
// Inputs
//   supabase/equipaciones-2026-27-frentes.json  (written by scripts/gen-equipaciones-frentes.mjs,
//                                                 which crawls each club's live FootyLogos page)
//   the live DB, to resolve product ids: products in the category with slug
//   'equipaciones' and season '2026-27', joined to teams for the team slug.
//
// Products whose team has no usable front view are SKIPPED and listed in
// supabase/equipaciones-2026-27-sin-frente.md. They are never written as an empty
// array, because that would blank out a product that still has a working store photo.
//
// The SQL is a plain `update ... set images = '[...]'::jsonb where id = '...'`, so
// running it twice writes the same value again and changes nothing.
//
// Run: node scripts/build-frentes-sql.mjs
import { createClient } from '@supabase/supabase-js';
import { readFileSync, writeFileSync } from 'node:fs';

const FRENTES = 'supabase/equipaciones-2026-27-frentes.json';
const OUT = 'supabase/equipaciones-2026-27-frentes.sql';
const REPORT = 'supabase/equipaciones-2026-27-sin-frente.md';
const CATEGORY_SLUG = 'equipaciones';
const SEASON = '2026-27';

const env = Object.fromEntries(
  readFileSync('.env.local', 'utf8').split(/\r?\n/).filter(Boolean)
    .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_ANON_KEY);

const { data: cat, error: catErr } = await sb.from('categories').select('id').eq('slug', CATEGORY_SLUG).maybeSingle();
if (catErr) throw catErr;
if (!cat) throw new Error(`category ${CATEGORY_SLUG} not found`);

const { data: rows, error: prodErr } = await sb
  .from('products')
  .select('id, title, team_id, teams ( slug, name )')
  .eq('category_id', cat.id)
  .eq('season', SEASON)
  .order('id');
if (prodErr) throw prodErr;

const frentes = JSON.parse(readFileSync(FRENTES, 'utf8'));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;
// Comments stay ASCII-only so the file survives any encoding path into psql.
const ascii = (s) => String(s).normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^\x20-\x7E]/g, '?');

// Why a product got no front view, in the wording the human report needs.
function reasonFor(slug, f) {
  if (!f) return 'team absent from the crawl output';
  // The crawl probes more than one season suffix, so name what it actually requested
  // rather than implying a single season was checked.
  const tried = Array.isArray(f.seasons_tried) && f.seasons_tried.length
    ? f.seasons_tried.join(' and ')
    : 'every candidate season';
  if (f.page_status === 404) return `no FootyLogos page for this club (checked ${tried})`;
  if (f.page_status !== 200) return `crawl could not read the club page (${f.page_status})`;
  if (f.missing_covers.length) return `no cover published for variant(s): ${f.missing_covers.join(', ')}`;
  return 'every candidate cover failed the HTTP probe';
}

const blocks = [];
const skipped = [];
const noTeam = [];
for (const p of rows ?? []) {
  const slug = p.teams?.slug ?? null;
  if (!slug) {
    noTeam.push({ id: p.id, title: p.title, reason: 'product has no team (team_id is null)' });
    continue;
  }
  const f = frentes[slug];
  // Skip rather than write '[]': an empty array would wipe a product's current photo.
  if (!f || f.views.length === 0) {
    skipped.push({ slug, name: f?.name ?? p.teams.name, id: p.id, title: p.title, reason: reasonFor(slug, f) });
    continue;
  }
  const images = f.views.map((v) => v.url);
  const variants = f.views.map((v) => v.variant).join(', ');
  blocks.push({
    id: p.id,
    images,
    comment: `-- ${ascii(f.name)} | ${plural(f.views.length, 'variant', 'variants')} (${variants})`,
    sql: `update products p set images = ${q(JSON.stringify(images))}::jsonb\n  where p.id = ${q(p.id)};`,
  });
}

const totalImages = blocks.reduce((n, b) => n + b.images.length, 0);
const skippedByTeam = new Map();
for (const s of skipped) {
  if (!skippedByTeam.has(s.slug)) skippedByTeam.set(s.slug, { ...s, products: [] });
  skippedByTeam.get(s.slug).products.push(s);
}

const out = [];
out.push('-- ============================================================================');
out.push('-- KOVA catalog - 2026-27 kit FRONT VIEWS only (FootyLogos)');
out.push('-- Generated by scripts/build-frentes-sql.mjs from');
out.push('-- supabase/equipaciones-2026-27-frentes.json - DO NOT edit by hand.');
out.push(`-- ${blocks.length} products - ${totalImages} front views - ${skippedByTeam.size} teams skipped (no usable front view).`);
out.push('-- Each block sets images to the front view of every kit variant the team has,');
out.push('-- replacing the previous full-gallery array (22-42 angles per kit).');
out.push('-- Skipped teams keep their current imagery: see');
out.push('-- supabase/equipaciones-2026-27-sin-frente.md');
out.push('-- Idempotent: re-running writes the same values.');
out.push('-- Rollback: supabase/equipaciones-2026-27-frentes-rollback.json');
out.push('--   That snapshot holds the 279 equipaciones/2026-27 products as they were');
out.push('--   immediately before this SQL ran, so it restores the previous galleries.');
out.push('--   supabase/equipaciones-2026-27-backup.json is the older pre-FootyLogos Wix');
out.push('--   snapshot and is NOT the rollback for this change.');
out.push('-- ============================================================================');
out.push('begin;');
out.push('');
for (const b of blocks) {
  out.push(b.comment);
  out.push(b.sql);
  out.push('');
}
out.push('commit;');
out.push('');

writeFileSync(OUT, out.join('\n'));

// Teams that got a partial set: some variant published no cover, so the SQL writes
// only the variants that do have one and the gap is recorded for manual follow-up.
const partial = Object.entries(frentes)
  .filter(([, f]) => f.views.length > 0 && f.missing_covers.length > 0)
  .map(([slug, f]) => ({ slug, name: f.name, missing: f.missing_covers, got: f.views.map((v) => v.variant) }));

const md = [];
md.push('# Equipaciones 2026-27 sin vista frontal de FootyLogos');
md.push('');
md.push(`Generado por \`scripts/build-frentes-sql.mjs\` el ${new Date().toISOString().slice(0, 10)}.`);
md.push('');
md.push(`Estos productos **no** aparecen en \`supabase/equipaciones-2026-27-frentes.sql\` porque no se les pudo asignar`);
md.push('una vista frontal de FootyLogos. Conservan las fotos que ya tenían en la tienda, y necesitan una');
md.push('foto de producto manual antes de volver a intentarlo.');
md.push('');
md.push(`- Productos actualizados: **${blocks.length}** (${totalImages} vistas frontales)`);
md.push(`- Productos omitidos: **${skipped.length}** en **${skippedByTeam.size}** equipos`);
md.push(`- Productos sin equipo: **${noTeam.length}**`);
md.push('');

if (skippedByTeam.size) {
  md.push('## Equipos sin vista frontal');
  md.push('');
  md.push('| Equipo | slug | Producto | Motivo |');
  md.push('| --- | --- | --- | --- |');
  for (const s of [...skippedByTeam.values()].sort((a, b) => a.slug.localeCompare(b.slug))) {
    md.push(`| ${ascii(s.name)} | \`${s.slug}\` | \`${s.id}\` | ${ascii(s.reason)} |`);
  }
  md.push('');
}

if (partial.length) {
  md.push('## Cobertura parcial');
  md.push('');
  md.push('Estos equipos reciben imagenes, pero les falta alguna variante porque FootyLogos');
  md.push('no publica portada para ella. Conviene revisar esas variantes a mano.');
  md.push('');
  md.push('| Equipo | slug | Variantes con portada | Variantes sin portada |');
  md.push('| --- | --- | --- | --- |');
  for (const p of partial) {
    md.push(`| ${ascii(p.name)} | \`${p.slug}\` | ${p.got.join(', ')} | ${p.missing.join(', ')} |`);
  }
  md.push('');
}

if (noTeam.length) {
  md.push('## Productos sin equipo asignado');
  md.push('');
  md.push('| Producto | Titulo | Motivo |');
  md.push('| --- | --- | --- |');
  for (const p of noTeam) md.push(`| \`${p.id}\` | ${ascii(p.title)} | ${ascii(p.reason)} |`);
  md.push('');
}

writeFileSync(REPORT, md.join('\n'));

const variantMix = {};
for (const b of blocks) {
  const key = b.comment.match(/\(([^)]*)\)/)[1].replace(/, ?/g, ', ');
  variantMix[key] = (variantMix[key] ?? 0) + 1;
}

console.log('=== 2026-27 front-view SQL ===');
console.log(`category               : ${CATEGORY_SLUG} (id ${cat.id})`);
console.log(`products season 2026-27: ${rows?.length ?? 0}`);
console.log(`products updated       : ${blocks.length}`);
console.log(`front views written    : ${totalImages}`);
console.log(`products without team  : ${noTeam.length}`);
console.log(`teams skipped          : ${skippedByTeam.size} (${skipped.length} products)`);
console.log(`teams partial cover    : ${partial.length}${partial.length ? ` (${partial.map((p) => `${p.slug}: no ${p.missing.join('/')}`).join(', ')})` : ''}`);
if (skippedByTeam.size) console.log(`    ${[...skippedByTeam.keys()].sort().join(', ')}`);
console.log(`variant mix            : ${Object.entries(variantMix).map(([k, n]) => `${k} x${n}`).join(' | ')}`);
console.log(`wrote ${OUT}`);
console.log(`wrote ${REPORT}`);
